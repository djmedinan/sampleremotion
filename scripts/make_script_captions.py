#!/usr/bin/env python3
"""Time script captions without a voice track: words are spread over each window in proportion to their length.
usage: make_script_captions.py script.json out.ts
script.json: {"keys": ["ganas", ...], "windows": [{"from": 0, "to": 3, "text": "..."}, ...]}
Once a real voice recording exists, use Whisper + make_reel_data.py instead.
"""
import json, sys, unicodedata

spec = json.load(open(sys.argv[1]))
norm = lambda s: "".join(c for c in unicodedata.normalize("NFD", s.lower()) if c.isalpha() and not unicodedata.combining(c))
KEYS = set(map(norm, spec["keys"]))
words = []
for w in spec["windows"]:
    toks = w["text"].split()
    weight = [len(t.strip(".,;:")) + 2 + (3 if t[-1] in ".,;:" else 0) for t in toks]
    total, t = sum(weight), w["from"]
    for tok, wt in zip(toks, weight):
        d = (w["to"] - w["from"]) * wt / total
        words.append({"t": tok.rstrip(".,;:").upper(), "s": round(t, 3), "e": round(t + d, 3),
                      "key": norm(tok) in KEYS, "end": tok[-1] in ".,;:"})
        t += d
groups, g = [], []
for w in words:
    g.append(w)
    if len(g) >= 3 or w["end"] or (len(g) == 2 and sum(len(x["t"]) for x in g) > 11):
        groups.append(g); g = []
if g: groups.append(g)
caps = [{"words": x, "from": x[0]["s"], "to": x[-1]["e"]} for x in groups]
for i in range(len(caps) - 1): caps[i]["to"] = caps[i + 1]["from"]
caps[-1]["to"] = spec["windows"][-1]["to"]
open(sys.argv[2], "w").write(
    "// Generated by scripts/make_script_captions.py (seconds)\n"
    f"export const SEGMENTS = [] as const;\nexport const CAPTIONS = {json.dumps(caps, ensure_ascii=False)} as const;\n"
    f"export const TOTAL_SECONDS = {spec['windows'][-1]['to']:.3f};\n")
print(len(caps), "caption groups,", len(words), "words")
