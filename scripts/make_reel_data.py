#!/usr/bin/env python3
"""Build jump-cut segments + word-by-word caption groups from Whisper word timings.
usage: make_reel_data.py words.json out.ts duration_seconds [keywords,comma,separated]
words.json: [{"t": " Hola", "s": 0.0, "e": 0.3}, ...]
"""
import json, sys, unicodedata

words_path, out_path, dur = sys.argv[1], sys.argv[2], float(sys.argv[3])
KEYS = set(k.strip() for k in (sys.argv[4] if len(sys.argv) > 4 else "").split(",") if k.strip())
LEAD, TAIL, GAP = 0.03, 0.05, 0.09  # seconds kept before/after speech; gaps longer than GAP are cut

def norm(s):
    s = unicodedata.normalize("NFD", s.lower())
    return "".join(c for c in s if c.isalpha() and not unicodedata.combining(c))

W = json.load(open(words_path))
segs, cur = [], None
for w in W:
    if cur and w["s"] - cur[1] <= GAP:
        cur[1] = w["e"]
    else:
        cur = [w["s"], w["e"]]
        segs.append(cur)
segs = [[max(0, a - LEAD), min(dur, b + TAIL)] for a, b in segs]
for i in range(1, len(segs)):
    segs[i][0] = max(segs[i][0], segs[i - 1][1])

offs, t = [], 0.0
for a, b in segs:
    offs.append(t)
    t += b - a
total = t

def m(x):
    for (a, b), o in zip(segs, offs):
        if a - 1e-6 <= x <= b + 1e-6:
            return o + x - a
    raise ValueError(x)

words = []
for w in W:
    s = m(w["s"] + 0.001)
    e = m(min(w["e"], next(b for a, b in segs if a <= w["s"] + 0.001 <= b)))
    txt = w["t"].strip()
    words.append({"t": txt.rstrip(".,;:").upper(), "s": round(s, 3), "e": round(e, 3),
                  "key": norm(txt) in KEYS, "end": txt[-1] in ".,;:?!"})

groups, g = [], []
for w in words:
    g.append(w)
    if len(g) >= 3 or w["end"] or (len(g) == 2 and sum(len(x["t"]) for x in g) > 11):
        groups.append(g); g = []
if g: groups.append(g)
caps = [{"words": x, "from": x[0]["s"], "to": x[-1]["e"]} for x in groups]
for i in range(len(caps) - 1):
    caps[i]["to"] = caps[i + 1]["from"]
caps[-1]["to"] = total

cuts = [round(o, 3) for o in offs]
open(out_path, "w").write(
    "// Generated by scripts/make_reel_data.py (seconds)\n"
    f"export const SEGMENTS = {json.dumps([[round(a,3),round(b,3)] for a,b in segs])} as const;\n"
    f"export const CUTS = {json.dumps(cuts)} as const;\n"
    f"export const CAPTIONS = {json.dumps(caps, ensure_ascii=False)} as const;\n"
    f"export const TOTAL_SECONDS = {total:.3f};\n")
print(len(segs), "segments", round(total, 2), "s of", dur, "| groups", len(caps))
